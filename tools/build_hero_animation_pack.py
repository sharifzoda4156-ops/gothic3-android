"""Pack approved whole-character drawings. No generative or recoloring step.

Usage: python tools/build_hero_animation_pack.py /path/to/sources
Sources: idle.png (2x2 turnaround), walk.png/punch.png/cast.png (4x4).
Requires Pillow and numpy. Outputs deterministic, aligned game sheets and inventory.
"""
from pathlib import Path
import hashlib,json,sys
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'app/src/midlet/resources/hd/characters/hero'
CELL=(320,320)
BASELINE=304
BODY_HEIGHT=232
# Model 100.mdl: slot 0 back, 1 right (mirrored legacy left), 2 front, 3 left.
DIRECTIONS=['back','right','front','left']
SOURCE_ROWS={'front':0,'right':1,'back':2,'left':3}

def normalize(image):
    data=np.asarray(image.convert('RGBA')).copy()
    # Generated transparency sometimes leaves tiny saturated matte fringes.
    # Limit removal to low-alpha fringe pixels; keep opaque burgundy clothing.
    fringe=(data[:,:,3]<160)&(((data[:,:,0]>150)&(data[:,:,1]<75)&(data[:,:,2]<75))|((data[:,:,1]>150)&(data[:,:,0]<100)&(data[:,:,2]<100)))
    data[(data[:,:,3]<16)|fringe,3]=0
    alpha=data[:,:,3]
    ys,xs=np.nonzero(alpha>96)
    if len(xs)<100:raise ValueError('Empty/invalid figure')
    left,right,top,bottom=int(xs.min()),int(xs.max()+1),int(ys.min()),int(ys.max()+1)
    # Robust boot/ground anchor ignores wispy casting particles beside the hands.
    low=(ys>top+(bottom-top)*.88)
    foot_x=float(np.median(xs[low]));foot_y=bottom
    scale=BODY_HEIGHT/(bottom-top)
    # Preserve aspect ratio; leave room for extended arms within the cell.
    span=max(foot_x-left,right-foot_x)
    scale=min(scale,(CELL[0]/2-4)/span)
    crop=Image.fromarray(data).crop((left,top,right,bottom))
    size=(max(1,round(crop.width*scale)),max(1,round(crop.height*scale)))
    crop=crop.resize(size,Image.Resampling.LANCZOS)
    x=round(CELL[0]/2-(foot_x-left)*scale);y=BASELINE-size[1]
    if x<0 or y<0 or x+size[0]>CELL[0] or y+size[1]>CELL[1]:raise ValueError('Figure exceeds cell')
    out=Image.new('RGBA',CELL);out.alpha_composite(crop,(x,y));return out

def crop_cell(image,col,row,cols,rows):
    x0=round(col*image.width/cols);x1=round((col+1)*image.width/cols)
    y0=round(row*image.height/rows);y1=round((row+1)*image.height/rows)
    return image.crop((x0,y0,x1,y1))

def build(source):
    DEST.mkdir(parents=True,exist_ok=True)
    images={n:Image.open(source/(n+'.png')).convert('RGBA') for n in ('idle','walk','punch','cast')}
    if any(im.getchannel('A').histogram()[0]<100 for im in images.values()):raise ValueError('Source background must be transparent')
    lines=['# Generated by tools/build_hero_animation_pack.py; selectors are model set and direction/action slot.','version=1']
    report={'sources':{n:hashlib.sha256((source/(n+'.png')).read_bytes()).hexdigest() for n in images},'coverage':[],'sheets':{}}
    for action in images:
        for direction in DIRECTIONS:
            if action=='idle':
                col,row={'front':(0,0),'right':(1,0),'back':(0,1),'left':(1,1)}[direction]
                frames=[normalize(crop_cell(images[action],col,row,2,2))]
            else:
                frames=[normalize(crop_cell(images[action],col,SOURCE_ROWS[direction],4,4)) for col in range(4)]
            sheet=Image.new('RGBA',(CELL[0]*len(frames),CELL[1]))
            for i,frame in enumerate(frames):sheet.alpha_composite(frame,(i*CELL[0],0))
            name=action+'-'+direction+'.png';sheet.save(DEST/name,optimize=True)
            report['sheets'][name]={'width':sheet.width,'height':sheet.height,'frames':len(frames),'sha256':hashlib.sha256((DEST/name).read_bytes()).hexdigest()}
    for model_set in (0,3):
        for slot in range(16):
            if slot>=12 and model_set==0:continue # retain genuine falling/hurt poses
            action='idle' if slot<4 else 'walk' if slot<8 else 'punch' if model_set==0 else 'cast'
            direction=DIRECTIONS[slot%4];name=f's{model_set}_{slot}'
            durations='10' if action=='idle' else '3,3,3,3' if action=='walk' else '5,5,5,5'
            for key,value in {'sheet':action+'-'+direction+'.png','set':model_set,'slot':slot,'layout':0,'appearance9':'*','appearance10':'*','frameWidth':CELL[0],'frameHeight':CELL[1],'columns':1 if action=='idle' else 4,'width':40,'height':40,'pivotX':20,'pivotY':38,'durations':durations,'loop':str(action in ('idle','walk')).lower(),'mirror':'false'}.items():lines.append(f'{name}.{key}={value}')
            report['coverage'].append({'set':model_set,'slot':slot,'action':action,'direction':direction})
    (DEST/'animation.properties').write_text('\n'.join(lines)+'\n')
    (DEST/'inventory.json').write_text(json.dumps(report,indent=2)+'\n')
    print(f'Packed {len(report["sheets"])} sheets, {sum(v["frames"] for v in report["sheets"].values())} drawings, {len(report["coverage"])} animation selectors')
if __name__=='__main__':build(Path(sys.argv[1]))
